const fs = require("node:fs");
const path = require("node:path");
const { getStarterBreeds } = require("../lib/game/starter-breeds");

function buildAdoptionSeed(records) {
  const json = JSON.stringify(getStarterBreeds(records)).replace(/'/g, "''");
  return `-- Source: data/domestic-pigeons.json. Generated by scripts/seed-adoption.js.
UPDATE public.game_species SET is_starter = false WHERE is_starter;
INSERT INTO public.game_species (
  id, name, kind, parent_species_id, scientific_name, description, image,
  rarity, is_starter, source_url, description_source, description_url, image_attribution
)
SELECT id, name, kind, parent_species_id, scientific_name, description, image,
  rarity, is_starter, source_url, description_source, description_url, image_attribution
FROM jsonb_to_recordset('${json}'::jsonb) AS breed (
  id text, name text, kind text, parent_species_id text, scientific_name text, description text, image text,
  rarity text, is_starter boolean, source_url text, description_source text, description_url text, image_attribution jsonb
)
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name, kind = EXCLUDED.kind, parent_species_id = EXCLUDED.parent_species_id,
  scientific_name = EXCLUDED.scientific_name, description = EXCLUDED.description, image = EXCLUDED.image,
  is_starter = EXCLUDED.is_starter, source_url = EXCLUDED.source_url,
  description_source = EXCLUDED.description_source, description_url = EXCLUDED.description_url,
  image_attribution = EXCLUDED.image_attribution;
`;
}

if (require.main === module) {
  const migrationPath = path.join(__dirname, "../migrations/002_adoption.sql");
  const { records } = require("../data/domestic-pigeons.json");
  const sql = fs.readFileSync(migrationPath, "utf8").replace(
    /-- BEGIN GENERATED STARTERS\r?\n[\s\S]*?-- END GENERATED STARTERS/,
    () => `-- BEGIN GENERATED STARTERS\n${buildAdoptionSeed(records)}-- END GENERATED STARTERS`
  );
  fs.writeFileSync(migrationPath, sql, "utf8");
}

module.exports = { buildAdoptionSeed };
